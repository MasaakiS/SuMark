/**
 * 12-visual-regression.spec.js
 *
 * Visual Regression Testing (VRT) — ラウンドトリップ表示一致テスト
 *
 * テストの仕組み:
 *   1. setMarkdown(md) でコンテンツを挿入（編集時の状態）
 *   2. スクリーンショットを取得（保存前）
 *   3. getMarkdown() で Markdown を取得（保存）
 *   4. setMarkdown(保存した Markdown) で再描画（再オープン時の状態）
 *   5. スクリーンショットを取得（保存後）
 *   6. ピクセル単位で直接比較 → 差分があれば失敗
 *
 * ベースラインファイルは不要。毎回テスト内で保存前後を直接比較する。
 * 失敗時は test/playwright-results/vrt-diffs/ に差分画像を保存。
 */

const { test, expect } = require('./fixtures');
const { roundtripVRT } = require('./vrt-utils');

// ─── ヘルパー ─────────────────────────────────────
function vrt(title, markdown, options = {}) {
    test(title, async ({ app }) => {
        const result = await roundtripVRT(app.page, markdown, title, options);
        expect(result.pass, [
            `ラウンドトリップ差分: ${result.diffPixels}px (${result.diffPercent}%)`,
            result.reason || '',
            result.pass ? '' : '→ test/playwright-results/vrt-diffs/ に差分画像を保存済み',
        ].filter(Boolean).join('\n')).toBe(true);
    });
}

